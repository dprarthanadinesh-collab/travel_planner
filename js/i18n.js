let currentLang = 'en';

export function getLanguage() {
  return currentLang;
}

export function t(key) {
  const langPack = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return langPack[key] || TRANSLATIONS.en[key] || key;
}

export function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) {
    langCode = 'en';
  }
  currentLang = langCode;
  localStorage.setItem('voyagecraft_lang', langCode);

  // Set document language & text direction
  document.documentElement.setAttribute('lang', langCode);
  document.documentElement.setAttribute('dir', langCode === 'ar' ? 'rtl' : 'ltr');

  applyTranslations();
}

export function initI18n() {
  window.t = t;
  const savedLang = localStorage.getItem('voyagecraft_lang') || 'en';
  setLanguage(savedLang);

  const langSelect = document.getElementById('global-language-select');
  if (langSelect) {
    langSelect.value = currentLang;
    langSelect.addEventListener('change', (e) => {
      setLanguage(e.target.value);
      window.showToast?.(`Language changed to ${e.target.options[e.target.selectedIndex].text}`, 'info');
    });
  }
}

export function applyTranslations() {
  // Translate all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) {
      el.textContent = translation;
    }
  });

  // Translate all input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      el.setAttribute('placeholder', translation);
    }
  });

  // Translate all title attributes with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translation = t(key);
    if (translation) {
      el.setAttribute('title', translation);
    }
  });
}
